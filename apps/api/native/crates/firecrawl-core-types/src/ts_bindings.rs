//! Renders deterministic TypeScript declarations for all open-source types
//! crossing the native boundary. `pnpm ts-bindings` writes them to
//! `apps/api/native/core-types.d.ts`, which `napi build` prepends to
//! `index.d.ts` via `napi.dtsHeaderFile`.

use std::collections::BTreeMap;

use ts_rs::{Config, TS, TypeVisitor};

use crate::{
  AttributeRequest, CoreNativeFailure, CoreParser, CoreParserKind, DeriveCoreHtmlRequest,
  DeriveCoreHtmlResult, ExtractedAttribute, NativeCallContext, ParseRawDocumentRequest,
  ParseRawDocumentResult,
};

struct Collector<'a> {
  cfg: &'a Config,
  decls: BTreeMap<String, String>,
  clashes: Vec<String>,
}

impl TypeVisitor for Collector<'_> {
  fn visit<T: TS + 'static + ?Sized>(&mut self) {
    if T::output_path().is_none() {
      return;
    }

    let name = T::ident(self.cfg);
    let decl = format!(
      "{}export {}",
      T::docs().unwrap_or_default(),
      T::decl(self.cfg)
    );
    if let Some(existing) = self.decls.get(&name) {
      if *existing != decl {
        self.clashes.push(name);
      }
      return;
    }

    self.decls.insert(name, decl);
    T::visit_dependencies(self);
  }
}

/// Renders the deterministic contents of `apps/api/native/core-types.d.ts`.
pub fn render_core_ts_bindings() -> Result<String, String> {
  let cfg = Config::new().with_large_int("number");
  let mut collector = Collector {
    cfg: &cfg,
    decls: BTreeMap::new(),
    clashes: Vec::new(),
  };

  collector.visit::<NativeCallContext>();
  collector.visit::<AttributeRequest>();
  collector.visit::<ExtractedAttribute>();
  collector.visit::<DeriveCoreHtmlRequest>();
  collector.visit::<DeriveCoreHtmlResult>();
  collector.visit::<CoreParserKind>();
  collector.visit::<CoreParser>();
  collector.visit::<ParseRawDocumentRequest>();
  collector.visit::<ParseRawDocumentResult>();
  collector.visit::<CoreNativeFailure>();

  if !collector.clashes.is_empty() {
    return Err(format!(
      "different types render as {}",
      collector.clashes.join(", ")
    ));
  }

  let mut out = String::from(
    "/* auto-generated by NAPI-RS */\n/* eslint-disable */\n\n\
     // Core native types, generated by ts-rs from apps/api/native/crates/firecrawl-core-types.\n\
     // Regenerate with `pnpm ts-bindings` in apps/api/native.\n\
     // prettier-ignore\n\
     export declare namespace CoreNative {\n",
  );
  for decl in collector.decls.values() {
    for line in decl.lines() {
      out.push_str("  ");
      out.push_str(line);
      out.push('\n');
    }
  }
  out.push_str("  export type CoreNativeError = CoreNativeFailure;\n");
  out.push_str("  export type CoreNativeErrorCode = CoreNativeFailure[\"code\"];\n");
  out.push_str("}\n");
  Ok(out)
}
